L1_ANTI_AI_CONSTRAINTS = """【L1·作品定位·网文（最高优先，先于一切风格要求）】
本书是**网络小说（网文）**，不是传统文学、不是纯文学、不是作文。读者是手机端大众读者，阅读是碎片化快读。因此：
- 说人话，让读者一眼看懂。**不需要文学素养、不需要高大上词汇、不需要文青腔、不需要金句**——任何"显示文笔/修养"的描写不是加分项，是减分项；
- 快节奏：每章必须有事件推进和钩子，开头 300 字进戏；拖沓、铺垫、注水就是弃书点；
- 信息直给：读者没耐心猜。需要琢磨的词、隐晦的表达、绕弯的比喻一律删；
- 对话像人说话，直白不绕；场景动作直接写，不要绕着写；
- 写每一句时用网文读者的尺子问自己：**手机端读者扫一眼能不能秒懂？删掉这句节奏会不会更快？** 秒懂 + 更快 → 保留；要琢磨 / 拖节奏 → 删。

【L1·通用写作硬约束（必须遵守）】
- 语言直接，少用修饰性词汇，避免散文化的美文写法。
- 多写"正在发生"的动作，少写静态描述；保持叙事推进感。
- 【叙述经济性·每句都要拉得动剧情】每个环境/氛围/动作/心理细节都要服务当页的人物状态、情绪、伏笔或事件推进，且通常当场或近几章有落点。判断标准：删掉这句，本章情节、人物、情绪、伏笔无任何变化 → 就是注水，必须删或改写成与人物/情节相关的细节。重点防五类：
  - 无落点空镜：孤立的环境句（"窗外是解放路，车喇叭一声接一声""太阳很大，蝉声一阵接一阵""办公室的吊扇正转得起劲，满桌的纸页被风掀得哗啦响"这类不绑定人物观察/情绪、不构成意象、不给后文埋点的纯环境句）一律删；
  - 纯舞台调度：零信息的动作记录（"坐下，包放在脚边"这类不暴露状态、不推进情节的调度）。环境细节要么与人物当下的观察/情绪绑定，要么为后文埋点，否则不写；
  - 无信息等待：干等一件与剧情无关的事（"蹲了十分钟，等太阳把钥匙孔照亮"这类「时间+等待+环境」的等）一律删；等待必须等的是有剧情落点的事，且等待本身要带出人物状态或信息；
  - 日常调度链：开门/开吊扇/烧水/擦桌子/扫地/收拾店面这类零信息收拾动作，成串出现即注水（"他先进去开了吊扇，又拎起暖水瓶摇了摇，半瓶底。他先没烧水。"）整段删；这类信息若确有必要，压进一句带过；
  - 开场调度戏：章节开头以"到点开门、收拾店面、等待环境变化"开场（"林砚秋七点就到。大门刚开，他蹲在台阶上等太阳把钥匙孔照亮"）是 AI 最爱写的注水开场，前 300 字应直接进戏（冲突/对话/异常/金手指出场），禁止用开门、等待、收拾做开场。
- 有限视角：只写当前 POV 角色能看到/知道的信息，禁止全知旁白、禁止透露未登场角色与后续剧情。
- 避免文学腔与装深沉；口语化自然流畅，不要文艺腔。
- 禁止 AI 套话（"在这个充满……的世界里""仿佛命运的齿轮开始转动"等陈词滥调）。
- 禁止总结性结尾（不要用一段话概括本章发生了什么）。
- 不要为了完成任务而写作；不要急于推进情节，让细节和画面写充分。

【L1·标点/句式频率硬约束（必须遵守）】
- 【破折号限频】全章“——”最多 3 处，破折号只能用于真正的语气急转或补充；禁止“写完 X，破折号后再把 X 解释一遍”（如“目光落在他的新皮鞋上——皮鞋是今天早上才擦过的”）。这种后置解说是 AI 最爱犯的腔调，把读者当傻子，出现即删。
- 【禁空泛比喻】比喻必须服务当下画面/情绪、有具体所指。禁止套壳比喻：像……一样/似的、“热得像蒸笼”“像烧红的烙铁”这类无新信息的替换词，一律删或换成具体细节；全章“像”字比喻不超过 2 处，宁可白描也不要硬凑喻体。
- 【禁甩尾句式】禁止“他张了张嘴，没说话”“嘴唇动了动，没出声”“他又试了三次，没改”“拳头攥紧，没挥出去”这类固定“动作+顿+否定收尾”句式——**出现一次即不合格**，直接删掉或换成有信息量的后续动作/对话推进（接下一句台词、转身去拿东西、把话咽回去再岔开话题），不要靠这个句式攒“克制感”。
- 【禁止解说型旁白】刚写完的动作、数字、局面，不得再补一句旁白解释它的含义（如“还剩一千五，离投资还差一星”“三百五。他算了算，够交房租和吃饭”——数字给读者即可，够不够让读者自己判断）；读者能自己算出来的、能从动作看出来的，交给读者。需要传递的信息用场景/对话呈现，作者不下场解说。

【L1·反「AI 味」量化自检（初稿阶段就要达标，不要留给修订）】
AI 检测器抓的从来不是内容，而是"统计上的整齐"。写完请逐条自检：
1. 句长必须起伏：3–8 字的极短句（独立成句）与 40 字以上的长句都要出现，
   极短句占比目标 ≥15%；任何连续 5 句都落在 15–30 字之间，就算不合格，必须打断。
2. 转折/因果连接词（但是、然而、不过、因此、所以、于是、而且、同时、尽管、虽然）
   密度 ≤3.5 次/千字。能用短句并列、语序变化、直接动作表达的，不要加连接词。
3. 禁止排比三连、禁止"总—分—总"、禁止段落等长：段落 1–6 句不等，允许单句成段。
4. 允许口语的不完美：偶尔重复用词、稍啰嗦的碎句、说到一半的停顿
   （"他顿了顿""话到嘴边又咽回去"）。不要每句都信息密集，不要句句都想写成金句。
5. 不要每段都有"感悟"或抒情升华；情绪用具体的动作、物件、身体反应来写，
   少用"仿佛/似乎/宛如/犹如"这类模糊副词。
6. 对话要像人说话：可以省略、可以答非所问、可以被打断或抢话，
   不要每句对话都完整、都点题、都推进信息。
7. 结尾停在具体画面、动作或一句对话上；不要总结、不要升华、不要展望。
8. 【AI 味句式禁写清单（逐类自查，出现即删改；程序检测器会逐句标出）】
   - "不是 X 而是 Y" 转折强调句式（如"他不是生气，而是心寒"）：换成直接的动作/对话表达；
   - 抽象抒情堆砌："某种说不清的……""一种莫名的……"类无实指情绪词，删掉或换成具体身体反应；
   - 空镜式收尾："他望向远方""看向窗外"类无信息量的姿态收尾；
   - 陷入沉思式收尾："陷入沉思""若有所思"类，删掉或改成具体下一步动作；
   - 金句体升华："或许这就是人生/命运/成长……"类结尾升华，一律删；
   - "此刻/这一瞬间/刹那间"高频堆叠：同段内出现 2 次以上就删到 1 次或全删；
   - 同一短句原样重复（机械排比），如"他握紧了刀，他握紧了刀，"。"""
