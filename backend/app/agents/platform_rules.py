def format_genres_direction(genres: list[str] | None) -> str:
    """把题材标签列表拼成写作方向指引；空/未知标签不阻塞，返回提示或占位。"""
    if not genres:
        return "题材：未标注（作者未选择题材，按通用网文节奏与签约标准把握，重点保证故事可读性）。"
    lines = []
    for g in genres:
        d = GENRE_DIRECTIONS.get(g.strip())
        if d:
            lines.append(d)
        else:
            lines.append(f"{g}（作者自定义题材，按该题材通行的写作惯例与读者期待把握）")
    return "【题材（多选，写作方向指引，全部生效）】" + " ".join(lines)


