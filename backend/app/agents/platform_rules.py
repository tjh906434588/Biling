def format_genres_direction(genres: list[str] | None) -> str:
    """把题材标签列表拼成写作方向指引；空/未知标签不阻塞，返回提示或占位。"""
    if not genres:
        return "题材：未标注（作者未选择题材，按通用网文节奏与签约标准把握，重点保证故事可读性）。"
    lines = []
    for g in genres:
        d = GENRE_DIRECTIONS.get(g.strip())
        if d:
            lines.append(d)
        else:
            lines.append(f"{g}（作者自定义题材，按该题材通行的写作惯例与读者期待把握）")
    return "【题材（多选，写作方向指引，全部生效）】" + " ".join(lines)


# ── 题材特化·叙事规则（按 background_type × genres 条件注入，仅对"现实事业流"生效）──
# 与 GENRE_DIRECTIONS（题材软性方向）不同：这里是"题材函数"级的结构性叙事规则，
# 从《天赋洞察》/《人生从裸辞开始》/《张雪峰》等都市现实事业流样本校准而来，
# 只对现实事业流成立；纯架空/玄幻仙侠/全民神祗等其它类型一律不注入，避免跨题材误伤。
# 触发口径：background_type == realistic，且题材标签含下列之一（都市/职场/教育/创业/现实）。
# 不选"校园"：校园言情/青春成长类不适用"一章一案例/信息差冲突源"等事业流规则。
REALISTIC_CAREER_GENRES = {"都市", "职场", "教育", "创业", "现实"}
# 负面过滤：即使标了 realistic + 都市，题材含超凡/架空标签（都市异能/都市奇幻/都市科幻/玄幻/仙侠等）
# 也不注入事业流规则——避免把"现实事业流"的叙事假设（现实回报/日常切入/信息差冲突源）误用于超凡题材。
NON_REALISTIC_GENRES = {"异能", "玄幻", "仙侠", "奇幻", "灵异", "武侠", "科幻"}

GENRE_STORYTELLING_REALISTIC_CAREER = """【题材特化·现实事业流（仅本书适用）】本书是现实题材的事业推进流（教育/职场/创业等行业经营向），以下规则只对本类题材成立，写作时遵循：
- 一章一事件：每章聚焦一个完整的案例/事件（一次咨询案例、一次谈判、一个决策），从发生推进到结果收束，不贪多不注水；跨章靠事件与事件之间的连锁反应串联（前一个案例的口碑/结果成为下一个事件的引子）；
- 事件结构：真实事件按「事件→阻力（被质疑/出岔子/资源不足）→结果（成功或翻车）→口碑或连锁反应」推进，戏眼落在真实事件与真实结果上，不靠嘴炮与巧合撑场；
- 信息差/认知壁垒是核心冲突源：主角的竞争优势来自掌握别人不知道的信息与判断力（行业门道、规则盲区、认知误区），冲突大多围绕"别人不懂而主角懂、别人被坑而主角能救"展开；
- 现实回报：爽点落在可量化的现实结果上（签单、招生、口碑、数据、晋级），克制戏剧化巧合，回报靠真实奋斗过程换得；
- 开场偏好：以日常/对话/环境切入为主流（从日常事务或工作细节切入，慢慢收紧），危机开场仅作可选的一种。"""


def format_genre_storytelling_rules(background_type: str | None, genres: list[str] | None) -> str:
    """返回本书题材特化的叙事规则段；非现实事业流返回空串（不注入任何特化规则）。

    判断口径：background_type == realistic，且题材标签含 都市/职场/教育/创业/现实 之一；
    题材含 异能/玄幻/仙侠/奇幻/灵异/武侠/科幻 之一（都市异能、都市奇幻等超凡题材）则不注入。
    架空/玄幻/全民神祗等其它类型返回空串——特化规则不跨题材生效，避免规则冲突。
    """
    if background_type != "realistic":
        return ""
    gset = {g.strip() for g in (genres or []) if isinstance(g, str) and g.strip()}
    if not (gset & REALISTIC_CAREER_GENRES):
        return ""
    if gset & NON_REALISTIC_GENRES:
        return ""
    return GENRE_STORYTELLING_REALISTIC_CAREER
