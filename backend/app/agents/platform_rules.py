def _match_genre_families(background_type: str | None, genres: list[str] | None) -> list[dict]:
    """按 背景×题材 解析命中的题材族（应用背景限定 + 负面过滤）。"""
    gset = {g.strip() for g in (genres or []) if isinstance(g, str) and g.strip()}
    if not gset:
        return []
    bg = (background_type or "").strip()
    matched = []
    for fam in GENRE_FAMILY_REGISTRY:
        if not (gset & fam["genres"]):
            continue
        if fam["background"] and bg != fam["background"]:
            continue
        if gset & fam["exclude_genres"]:
            continue
        matched.append(fam)
    return matched


def format_genre_storytelling_rules(background_type: str | None, genres: list[str] | None) -> str:
    """返回本书命中的题材族全部结构性叙事约束段（多族命中则合并）；无命中返回空串。

    例如：realistic+都市/职场 → 现实事业流段；realistic+都市/异能 → 被负面过滤返回空串；
    alternate/pure_fantasy（全民神祗、玄幻仙侠等）→ 无命中，返回空串（不注入特化规则）。
    """
    blocks = [
        fam["storytelling"]
        for fam in _match_genre_families(background_type, genres)
        if fam.get("storytelling")
    ]
    return "\n\n".join(blocks)


# ── 开篇与金手指兑现节奏 · 蓝图师注入函数 ──
# 开篇方式与金手指兑现节奏本质是**题材函数**，不是普适硬约束，已并入 GENRE_FAMILY_REGISTRY 的 rhythm 字段：
# 蓝图师 build_context 运行时按本书 background_type × genres 命中题材族 → 取该族 rhythm；
# 未命中任何族（含全民神祗/玄幻仙侠等未归纳题材）→ 回退 GENRE_RHYTHM_DEFAULT 通用平台节奏。
def format_blueprint_rhythm_rules(background_type: str | None, genres: list[str] | None) -> str:
    """返回开篇与金手指兑现节奏段（蓝图师注入用）。

    按注册表命中题材族取 rhythm；无命中/无 rhythm 字段 → 通用平台节奏 GENRE_RHYTHM_DEFAULT。
    例：realistic+都市 → 写实克制兑现；realistic+都市/异能 → 负面过滤未命中 → 通用节奏；
    alternate/pure_fantasy（全民神祗、玄幻仙侠等）→ 未命中 → 通用节奏。
    """
    for fam in _match_genre_families(background_type, genres):
        if fam.get("rhythm"):
            return fam["rhythm"]
    return GENRE_RHYTHM_DEFAULT
